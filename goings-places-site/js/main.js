// ─── Scroll-triggered animations ─────────────
document.addEventListener('DOMContentLoaded', () => {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
      }
    });
  }, { threshold: 0.12 });

  document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));

  // ─── Navbar scroll effect ────────────────
  const navbar = document.querySelector('.navbar');
  if (navbar) {
    window.addEventListener('scroll', () => {
      navbar.classList.toggle('scrolled', window.scrollY > 40);
    });
  }

  // ─── Mobile menu ─────────────────────────
  const hamburger = document.querySelector('.hamburger');
  const mobileMenu = document.querySelector('.mobile-menu');
  if (hamburger && mobileMenu) {
    hamburger.addEventListener('click', () => {
      mobileMenu.classList.toggle('open');
      const spans = hamburger.querySelectorAll('span');
      if (mobileMenu.classList.contains('open')) {
        spans[0].style.transform = 'rotate(45deg) translateY(7px)';
        spans[1].style.opacity = '0';
        spans[2].style.transform = 'rotate(-45deg) translateY(-7px)';
      } else {
        spans[0].style.transform = 'none';
        spans[1].style.opacity = '1';
        spans[2].style.transform = 'none';
      }
    });
    mobileMenu.querySelectorAll('a').forEach(link => {
      link.addEventListener('click', () => {
        mobileMenu.classList.remove('open');
        const spans = hamburger.querySelectorAll('span');
        spans[0].style.transform = 'none';
        spans[1].style.opacity = '1';
        spans[2].style.transform = 'none';
      });
    });
  }

  // ─── Animated Counters ───────────────────
  const counters = document.querySelectorAll('[data-count]');
  const countObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting && !entry.target.dataset.counted) {
        entry.target.dataset.counted = 'true';
        const end = parseInt(entry.target.dataset.count);
        const suffix = entry.target.dataset.suffix || '';
        const prefix = entry.target.dataset.prefix || '';
        let current = 0;
        const step = end / 120;
        const timer = setInterval(() => {
          current += step;
          if (current >= end) {
            entry.target.textContent = prefix + end + suffix;
            clearInterval(timer);
          } else {
            entry.target.textContent = prefix + Math.floor(current) + suffix;
          }
        }, 16);
      }
    });
  }, { threshold: 0.3 });
  counters.forEach(c => countObserver.observe(c));

  // ─── Form handling ───────────────────────
  const offerForm = document.getElementById('offer-form');
  const formCard = document.getElementById('form-card');
  const formSuccess = document.getElementById('form-success');
  if (offerForm) {
    offerForm.addEventListener('submit', (e) => {
      e.preventDefault();
      // Netlify handles the actual submission via its form detection
      // For the UI, show success state
      const formData = new FormData(offerForm);
      fetch('/', {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams(formData).toString()
      }).then(() => {
        if (formCard) formCard.style.display = 'none';
        if (formSuccess) formSuccess.classList.add('show');
      }).catch(() => {
        // Still show success UI even if fetch fails (Netlify will catch it)
        if (formCard) formCard.style.display = 'none';
        if (formSuccess) formSuccess.classList.add('show');
      });
    });
  }
});

